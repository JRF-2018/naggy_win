#!/usr/bin/env python3
# Generate internal/ujconv/tables.go from tools/unicode_japanese_tables.txt
# (the output of tools/dump_unicode_japanese.pl run with Unicode::Japanese).
import sys
src, dst = sys.argv[1], sys.argv[2]
tabs = {}
for line in open(src, encoding='utf-8'):
    f, a, b = line.rstrip('\n').split('\t')
    tabs.setdefault(f, []).append((a.split(), b.split()))
def lit(cps):
    return '"' + ''.join('\\u%04X' % int(x, 16) for x in cps) + '"'
names = {'z2h': 'z2hTable', 'h2z': 'h2zTable', 'hira2kata': 'hira2kataTable',
         'kata2hira': 'kata2hiraTable', 'pair-h2z': 'h2zPairTable'}
with open(dst, 'w', encoding='utf-8') as o:
    o.write('// Code generated by tools/gen_ujtables.py; DO NOT EDIT.\n\npackage ujconv\n\n')
    for f in ['z2h', 'h2z', 'hira2kata', 'kata2hira', 'pair-h2z']:
        o.write('var %s = map[string]string{\n' % names[f])
        for a, b in tabs.get(f, []):
            o.write('\t%s: %s,\n' % (lit(a), lit(b)))
        o.write('}\n\n')
